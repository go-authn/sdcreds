// String returns the id as 32 lower-case hex digits.
func (k KeyID) String() string { return fmt.Sprintf("%x", k[:]) }

// Scoped reports whether the key type binds the credential to a user.
func (k KeyID) Scoped() bool { return k == IDHostScoped }

// UsesHostKey reports whether the key type mixes in the host secret.
func (k KeyID) UsesHostKey() bool { return k == IDHost || k == IDHostScoped }

// Limits, all from cu.h and cu.c at v262.2.
const (
	// NameMax is CREDENTIAL_NAME_MAX = FDNAME_MAX (cu.h:9, fd-util.h:11).
	NameMax = 255
	// PlaintextMax is CREDENTIAL_SIZE_MAX, 1 MiB (cu.h:12).
	PlaintextMax = 1 << 20
	// EncryptedMax is CREDENTIAL_ENCRYPTED_SIZE_MAX, plaintext + 128 KiB (cu.h:21).
	EncryptedMax = PlaintextMax + 128<<10
	// FieldMax is CREDENTIAL_FIELD_SIZE_MAX, the bound for IV, block and tag
	// sizes (cu.c:778).
	FieldMax = 16 << 10
	// HostSecretMax is the biggest host secret file accepted (cu.c:617).
	HostSecretMax = 16 << 20

	keySize   = 32 // AES-256 (cu.c:1104)
	blockSize = 1  // EVP_CIPHER_get_block_size(aes-256-gcm), see DESIGN open question 1
	ivSize    = 12 // EVP_CIPHER_get_iv_length(aes-256-gcm)
	tagSize   = 16 // EVP_CIPHER_CTX_get_tag_length

	// scopeFlags is SCOPE_HASH_DATA_BASE_FLAGS: HAS_UID|HAS_MACHINE|HAS_USERNAME (cu.c:766-773).
	scopeFlags = 7

	// Infinity is USEC_INFINITY, the "no timestamp" value.
	Infinity = ^uint64(0)
)
