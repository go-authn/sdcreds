// Package sdcreds reads and writes the systemd credential format produced by
// "systemd-creds encrypt" (v262.2, src/shared/creds-util.c), byte for byte.
//
// Phase 1 covers the modes that need no TPM: null, host and host-scoped.
// Credentials sealed with a TPM2 or a public key are recognised and refused
// with an *UnsupportedModeError.
